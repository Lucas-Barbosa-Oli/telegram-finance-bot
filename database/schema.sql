-- Run on the bot's Supabase project before deploying v2.
-- Transactional, repeatable upgrade: existing records and IDs are preserved.
BEGIN;
CREATE TABLE IF NOT EXISTS public.transactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    amount numeric(12,2) NOT NULL,
    type text NOT NULL CHECK (type IN ('income','expense')),
    category text NOT NULL,
    description text,
    status text NOT NULL DEFAULT 'confirmed' CHECK (status IN ('planned','confirmed')),
    created_at timestamptz DEFAULT now()
);
ALTER TABLE public.transactions ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'confirmed';
ALTER TABLE public.transactions ADD COLUMN IF NOT EXISTS occurred_on date;
ALTER TABLE public.transactions ADD COLUMN IF NOT EXISTS source_chat_id bigint;
ALTER TABLE public.transactions ADD COLUMN IF NOT EXISTS source_message_id bigint;
ALTER TABLE public.transactions ADD COLUMN IF NOT EXISTS deleted_at timestamptz;
-- Old records only contain creation time; derive their date in the original bot timezone.
UPDATE public.transactions SET occurred_on =
    (coalesce(created_at, now()) AT TIME ZONE 'America/Sao_Paulo')::date
    WHERE occurred_on IS NULL;
ALTER TABLE public.transactions ALTER COLUMN occurred_on SET DEFAULT ((now() AT TIME ZONE 'America/Sao_Paulo')::date);
ALTER TABLE public.transactions ALTER COLUMN occurred_on SET NOT NULL;
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='transactions_status_check' AND conrelid='public.transactions'::regclass) THEN
        ALTER TABLE public.transactions ADD CONSTRAINT transactions_status_check CHECK (status IN ('planned','confirmed'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='transactions_positive_amount' AND conrelid='public.transactions'::regclass) THEN
        -- NOT VALID preserves historical anomalies but rejects invalid new writes.
        ALTER TABLE public.transactions ADD CONSTRAINT transactions_positive_amount CHECK (amount > 0 AND amount < 10000000000) NOT VALID;
    END IF;
END $$;
CREATE UNIQUE INDEX IF NOT EXISTS transactions_source_unique
    ON public.transactions(user_id, source_chat_id, source_message_id);
CREATE INDEX IF NOT EXISTS transactions_user_date_active
    ON public.transactions(user_id, occurred_on, id) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS transactions_user_id_active
    ON public.transactions(user_id, id DESC) WHERE deleted_at IS NULL;
ALTER TABLE public.transactions ENABLE ROW LEVEL SECURITY;
-- Telegram IDs are not Supabase Auth identities. Only the trusted backend gets access.
DROP POLICY IF EXISTS bot_anon_can_delete_transactions ON public.transactions;
DROP POLICY IF EXISTS bot_anon_can_insert_transactions ON public.transactions;
DROP POLICY IF EXISTS bot_anon_can_read_transactions ON public.transactions;
DROP POLICY IF EXISTS bot_anon_can_update_transactions ON public.transactions;
REVOKE ALL ON public.transactions FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON public.transactions TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.transactions_id_seq TO service_role;

CREATE TABLE IF NOT EXISTS public.finance_drafts (
    id uuid PRIMARY KEY,
    user_id bigint NOT NULL,
    source_chat_id bigint NOT NULL,
    source_message_id bigint NOT NULL,
    payload jsonb NOT NULL,
    expires_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS finance_drafts_user_expiry ON public.finance_drafts(user_id, expires_at);
ALTER TABLE public.finance_drafts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.finance_drafts FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, DELETE ON public.finance_drafts TO service_role;
NOTIFY pgrst, 'reload schema';
COMMIT;
